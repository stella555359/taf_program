#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Sync detection strategies from strategy_recommendations.xlsx to:
- kpi_custom_rules.xlsx (Default_Strategy column)
- kpi_classification_v2.xlsx (Detection_Strategy column)

strategy_recommendations.xlsx is generated by reclassify_strategies.py based on
historical data analysis, and should be the authoritative source.

Created: 2026-02-03 (ivy0203)
"""

import pandas as pd
from pathlib import Path

def sync_strategies():
    """Sync strategies from recommendations to other files"""
    
    recommendations_path = Path('lib/kpi_xml/strategy_recommendations.xlsx')
    custom_rules_path = Path('lib/kpi_xml/kpi_custom_rules.xlsx')
    classification_path = Path('lib/kpi_xml/kpi_classification_v2.xlsx')
    
    if not recommendations_path.exists():
        print(f"Error: {recommendations_path} not found")
        print("Run reclassify_strategies.py first to generate recommendations")
        return
    
    # Load recommendations
    rec_df = pd.read_excel(recommendations_path, sheet_name='All_Codes')
    print(f"Loaded {len(rec_df)} rows from strategy_recommendations.xlsx")
    
    # Build strategy map
    strategy_map = {}
    for _, row in rec_df.iterrows():
        code = str(row.get('Code', '')).strip()
        strategy = str(row.get('Recommended_Strategy', '')).strip()
        if code and strategy and strategy != 'nan':
            strategy_map[code] = strategy
    
    print(f"Built strategy map with {len(strategy_map)} codes")
    
    # Update kpi_classification_v2.xlsx
    if classification_path.exists():
        cls_df = pd.read_excel(classification_path)
        updated = 0
        for idx, row in cls_df.iterrows():
            code = str(row.get('Code', '')).strip()
            if code in strategy_map:
                current = str(row.get('Detection_Strategy', '')).strip()
                expected = strategy_map[code]
                if current != expected:
                    cls_df.loc[idx, 'Detection_Strategy'] = expected
                    updated += 1
        
        if updated > 0:
            cls_df.to_excel(classification_path, index=False)
            print(f"Updated {updated} strategies in kpi_classification_v2.xlsx")
        else:
            print("kpi_classification_v2.xlsx already in sync")
    
    # Update kpi_custom_rules.xlsx
    if custom_rules_path.exists():
        with pd.ExcelFile(custom_rules_path) as xls:
            sheets = {name: pd.read_excel(xls, sheet_name=name) for name in xls.sheet_names}
        
        if '1_Custom_Rules' in sheets:
            df = sheets['1_Custom_Rules']
            updated = 0
            for idx, row in df.iterrows():
                code = str(row.get('Code', '')).strip()
                if code in strategy_map:
                    current = str(row.get('Default_Strategy', '')).strip()
                    expected = strategy_map[code]
                    if current != expected:
                        df.loc[idx, 'Default_Strategy'] = expected
                        updated += 1
            
            if updated > 0:
                sheets['1_Custom_Rules'] = df
                with pd.ExcelWriter(custom_rules_path, engine='openpyxl') as writer:
                    for name, sheet_df in sheets.items():
                        sheet_df.to_excel(writer, sheet_name=name, index=False)
                print(f"Updated {updated} strategies in kpi_custom_rules.xlsx")
            else:
                print("kpi_custom_rules.xlsx already in sync")


if __name__ == '__main__':
    sync_strategies()
